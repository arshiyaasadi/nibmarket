interface SortedRule {
  min: number;
  max: number;
  province: string;
  region: string;
  span: number;
}

const SORTED_RULES: SortedRule[] = RULES_RAW.map(([min, max, province, region]) => ({
  min,
  max,
  province,
  region,
  span: max - min,
})).sort((a, b) => a.span - b.span);

/** Lookup by 5-digit routing prefix (11111–99999). */
export function lookupPostalRegion(prefix5: number): IranPostalRegion {
  if (!Number.isFinite(prefix5) || prefix5 < 10_000 || prefix5 > 99_999) {
    return UNKNOWN_POSTAL_REGION;
  }

  for (const rule of SORTED_RULES) {
    if (prefix5 >= rule.min && prefix5 <= rule.max) {
      return { province: rule.province, region: rule.region };
    }
  }

  return UNKNOWN_POSTAL_REGION;
}
